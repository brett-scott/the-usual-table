import { expect, test } from '@playwright/test';
import { roomIdFromHash, shortRoomHash } from '@casual/protocol';
import { expectOneScreen, openTableEntry, openTableOptions, rigShoe } from './fixtures';

test('table utilities remove clutter, expose Leave and give invitation copy feedback and fallback', async ({ page }, testInfo) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => {
    const state = window as unknown as { copiedLink?: string; rejectCopy?: boolean };
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { async writeText(value: string) {
      if (state.rejectCopy) throw new Error('Clipboard blocked');
      state.copiedLink = value;
    } } });
  });
  await openTableEntry(page); await page.getByLabel('What should we call you?').fill('Friendly host');
  await page.getByRole('button', { name: 'Create table', exact: true }).click();
  await expect(page.locator('[data-connection]')).toHaveAttribute('data-connection', 'connected');
  await expect(page.getByRole('heading', { name: /The shared table|The practice table/ })).toHaveCount(0);
  await expect(page.getByText('All the fun. None of the stakes.', { exact: true })).toHaveCount(0);
  await expect(page.locator('main footer')).toHaveCount(0);
  await expect(page.getByText(/^TABLE [A-F0-9]{6}$/)).toHaveCount(0);
  await expect(page.locator('header').getByRole('button', { name: /^(Rules|Card styles|Switch to .* table)$/ })).toHaveCount(0);
  const leave = page.getByRole('button', { name: 'Leave table', exact: true });
  await expect(leave).toBeVisible();
  const button = (await leave.boundingBox())!; const table = (await page.getByRole('region', { name: 'Blackjack table' }).boundingBox())!;
  expect(button.height).toBeGreaterThanOrEqual(44); expect(button.width).toBeGreaterThan(90);
  expect(button.x >= table.x + table.width || button.y + button.height <= table.y + 1, 'Leave is separate from gameplay, above or beside the felt').toBe(true);
  await expectOneScreen(page); await page.screenshot({ path: testInfo.outputPath('table-clean-utilities.png') });
  const invite = page.getByRole('button', { name: 'Invite', exact: true });
  await invite.click(); const dialog = page.getByRole('dialog', { name: 'Invite friends', exact: true });
  const shared = new URL(page.url()); shared.hash = shortRoomHash(roomIdFromHash(shared.hash)!);
  await expect(dialog).toBeVisible(); await expect(dialog.getByLabel('Invitation link')).toHaveValue(shared.href);
  await dialog.getByRole('button', { name: 'Copy link', exact: true }).click();
  await expect(dialog.getByRole('status')).toHaveText('Link copied. Send it to your friends.');
  expect(await page.evaluate(() => (window as unknown as { copiedLink: string }).copiedLink)).toBe(shared.href);
  await expect(page.locator('[data-connection]')).toHaveAttribute('data-connection', 'connected');
  await page.screenshot({ path: testInfo.outputPath('invite-link-copied.png') });
  await page.evaluate(() => { (window as unknown as { rejectCopy: boolean }).rejectCopy = true; });
  await dialog.getByRole('button', { name: 'Copy link', exact: true }).click();
  await expect(dialog.getByRole('status')).toContainText('copy it manually');
  const link = dialog.getByLabel('Invitation link'); await expect(link).toBeFocused();
  expect(await link.evaluate(el => (el as HTMLInputElement).selectionEnd)).toBe(shared.href.length);
  await page.keyboard.press('Escape'); await expect(invite).toBeFocused();
  await page.evaluate(() => { Object.defineProperty(navigator, 'clipboard', { configurable: true, value: undefined }); });
  await invite.click(); await expect(dialog.getByRole('status')).toBeEmpty();
  await dialog.getByRole('button', { name: 'Copy link', exact: true }).click();
  await expect(dialog.getByRole('status')).toContainText('copy it manually');
  await page.screenshot({ path: testInfo.outputPath('invite-manual-copy.png') });
  await dialog.getByRole('button', { name: 'Close invitation' }).click(); await expect(invite).toBeFocused();
  await expect(page.getByRole('region', { name: 'Game controls' }).getByRole('alert')).toHaveCount(0);
  expect(errors).toEqual([]);
  await leave.click(); await expect(page.getByRole('heading', { name: 'A game for every table.' })).toBeVisible();
});

test('Options has accessible subviews and local preferences preserve live cards and the running timer', async ({ page }, testInfo) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  const now = new Date('2026-10-31T00:00:00Z'); await page.clock.install({ time: now }); await page.clock.pauseAt(now);
  await rigShoe(page, ['5', '6', '6', '10', 'K', '3']);
  await openTableEntry(page); await page.getByLabel('What should we call you?').fill('Options player'); await page.keyboard.press('Enter');
  await page.getByRole('button', { name: 'Deal me in' }).click();
  const card = page.getByRole('region', { name: 'Your seat' }).getByRole('group', { name: 'Player hand cards' }).getByRole('img').first();
  const handle = await card.elementHandle(); const dealtAt = await card.getAttribute('data-deal-at');
  const revision = await page.locator('[data-revision]').getAttribute('data-revision');
  const options = await openTableOptions(page, 'Cards');
  await expect(options.getByRole('heading', { name: 'Card styles', exact: true })).toBeFocused();
  await options.getByLabel('Card face', { exact: true }).selectOption('large-index');
  await options.getByLabel('Card back', { exact: true }).selectOption('geometric');
  await page.clock.runFor(3000);
  await expect(page.locator('[role="timer"] strong')).toHaveText('17s');
  await expect(options).toContainText('Your hand timer keeps running.');
  await page.screenshot({ path: testInfo.outputPath('options-card-styles.png') });
  await options.getByRole('button', { name: 'Back to table options' }).click();
  await expect(options.getByRole('button', { name: 'Cards', exact: true })).toBeFocused();
  await options.getByRole('button', { name: 'Themes', exact: true }).click();
  await options.getByRole('radio', { name: 'Midnight', exact: true }).check();
  await expect(page.locator('[data-theme="midnight"][data-connection]')).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('options-table-themes.png') });
  await options.getByRole('button', { name: 'Back to table options' }).click();
  await expect(options.getByRole('button', { name: 'Themes', exact: true })).toBeFocused();
  await page.screenshot({ path: testInfo.outputPath('options-menu.png') });
  await options.getByRole('button', { name: 'Rules', exact: true }).click();
  await expect(options.getByRole('heading', { name: 'Rules', exact: true })).toBeFocused();
  await expect(options).toContainText('Hit resets the countdown to 20 seconds');
  await page.keyboard.press('Escape'); await expect(page.getByRole('button', { name: 'Table options', exact: true })).toBeFocused();
  const stand = page.getByRole('button', { name: 'Stand', exact: true }); await stand.focus();
  // A delayed native close notification must not steal the user's next focus.
  await page.locator('dialog[aria-label="Table options"]').dispatchEvent('close');
  await expect(stand).toBeFocused();
  expect(await handle!.evaluate(el => el.isConnected)).toBe(true); expect(await card.getAttribute('data-deal-at')).toBe(dealtAt);
  expect(await page.locator('[data-revision]').getAttribute('data-revision')).toBe(revision);
  await expect(card).toHaveAttribute('data-face', 'large-index'); await expect(card).toHaveAttribute('data-back', 'geometric');
  await expectOneScreen(page); await page.screenshot({ path: testInfo.outputPath('active-hand-midnight.png') });
});
